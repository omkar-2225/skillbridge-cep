export function extractSkillsFromResume(text: string): string[] {
  const lower = text.toLowerCase();
  const matched = new Set<string>();
  for (const [skillId, keywords] of Object.entries(KNOWN_SKILL_KEYWORDS)) {
    for (const kw of keywords) {
      if (lower.includes(kw)) {
        matched.add(skillId);
        break;
      }
    }
  }
  return Array.from(matched);
}

// Generate an overall 10-question assessment
// (3 Aptitude + 7 Technical/Resume-based across Easy, Medium, Hard)
export function generateStudentAssessment(params: {
  isFirstYear: boolean;
  resumeSkills?: string[];
}): Question[] {
  const { isFirstYear, resumeSkills = [] } = params;

  // Select 3 Aptitude questions: 1 Easy, 1 Medium, 1 Hard
  const aptEasy = APTITUDE_QUESTIONS.filter((q) => q.difficulty === "easy");
  const aptMed = APTITUDE_QUESTIONS.filter((q) => q.difficulty === "medium");
  const aptHard = APTITUDE_QUESTIONS.filter((q) => q.difficulty === "hard");

  const q1 = aptEasy[0];
  const q2 = aptMed[0];
  const q3 = aptHard[0];

  // Select 7 Technical questions:
  // Target: ~3 Easy, ~3 Medium, ~1 Hard
  let pool: Question[] = [];

  if (isFirstYear || resumeSkills.length === 0) {
    // 1st year foundation track
    pool = [
      ...(TECHNICAL_QUESTIONS.foundation || []),
      ...(TECHNICAL_QUESTIONS.python || []),
      ...(TECHNICAL_QUESTIONS.js || []),
      ...(TECHNICAL_QUESTIONS.ds || []),
    ];
  } else {
    // Collect from matched resume skills
    for (const s of resumeSkills) {
      if (TECHNICAL_QUESTIONS[s]) {
        pool.push(...TECHNICAL_QUESTIONS[s]);
      }
    }
    // Fallbacks if not enough questions
    if (pool.length < 7) {
      pool.push(...(TECHNICAL_QUESTIONS.ds || []));
      pool.push(...(TECHNICAL_QUESTIONS.js || []));
      pool.push(...(TECHNICAL_QUESTIONS.sql || []));
    }
  }

  // Deduplicate pool
  const uniquePool = Array.from(new Map(pool.map((q) => [q.id, q])).values());

  const techEasy = uniquePool.filter((q) => q.difficulty === "easy");
  const techMed = uniquePool.filter((q) => q.difficulty === "medium");
  const techHard = uniquePool.filter((q) => q.difficulty === "hard");

  const selectedTech: Question[] = [];

  // Pick up to 3 easy
  selectedTech.push(...techEasy.slice(0, 3));
  // Pick up to 3 medium
  selectedTech.push(...techMed.slice(0, 3));
  // Pick 1 hard
  if (techHard.length > 0) {
    selectedTech.push(techHard[0]);
  }

  // Ensure total technical is 7
  if (selectedTech.length < 7) {
    for (const q of uniquePool) {
      if (!selectedTech.find((x) => x.id === q.id)) {
        selectedTech.push(q);
        if (selectedTech.length === 7) break;
      }
    }
  }

  const finalQuestions = [q1, q2, q3, ...selectedTech.slice(0, 7)];

  // Order smoothly: Easy first, then Medium, then Hard
  const diffOrder = { easy: 1, medium: 2, hard: 3 };
  finalQuestions.sort((a, b) => diffOrder[a.difficulty] - diffOrder[b.difficulty]);

  return finalQuestions.slice(0, 10);
}

// Generate Company Zero Round Screening Test:
// Stage 1: Easy questions (3) -> Must score >= 35%
// Stage 2: Medium questions (3) -> Must score >= 75%
// Stage 3: Hard questions (EXACTLY 2) -> Final evaluation
export function generateZeroRoundTest(requiredSkills: string[]): {
  easy: Question[];
  medium: Question[];
  hard: Question[];
} {
  const allPool: Question[] = [];

  for (const s of requiredSkills) {
    if (TECHNICAL_QUESTIONS[s]) {
      allPool.push(...TECHNICAL_QUESTIONS[s]);
    }
  }

  // Supplement from DSA, Aptitude, JS, Python
  allPool.push(...(TECHNICAL_QUESTIONS.ds || []));
  allPool.push(...(TECHNICAL_QUESTIONS.sql || []));
  allPool.push(...(TECHNICAL_QUESTIONS.python || []));
  allPool.push(...(TECHNICAL_QUESTIONS.js || []));
  allPool.push(...APTITUDE_QUESTIONS);

  const unique = Array.from(new Map(allPool.map((q) => [q.id, q])).values());

  const easyList = unique.filter((q) => q.difficulty === "easy").slice(0, 3);
  const medList = unique.filter((q) => q.difficulty === "medium").slice(0, 3);
  const hardList = unique.filter((q) => q.difficulty === "hard").slice(0, 2); // Exactly 2 questions for hard!

  return {
    easy: easyList,
    medium: medList,
    hard: hardList,
  };
}

